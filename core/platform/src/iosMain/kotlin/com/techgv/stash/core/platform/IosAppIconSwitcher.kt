package com.techgv.stash.core.platform

import com.techgv.stash.core.model.AppIcon
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.suspendCancellableCoroutine
import kotlinx.coroutines.withContext
import platform.Foundation.NSError
import platform.UIKit.UIApplication
import platform.UIKit.alternateIconName
import platform.UIKit.setAlternateIconName
import platform.UIKit.supportsAlternateIcons
import kotlin.coroutines.resume

/**
 * `setAlternateIconName`. Leather is the primary icon (`nil`); the others are the asset catalog's alternate icon sets
 * `AppIcon-Night`, `AppIcon-Parchment` and `AppIcon-Ink` (generated by `iosApp/scripts/generate-app-icons.swift`).
 */
class IosAppIconSwitcher : AppIconSwitcher {
    // Read when asked: UIApplication does not exist in a test runner.
    override val isSupported: Boolean get() = UIApplication.sharedApplication.supportsAlternateIcons

    override suspend fun set(icon: AppIcon): Boolean = withContext(Dispatchers.Main) {
        val app = UIApplication.sharedApplication
        val name = alternateIconName(icon)
        when {
            !app.supportsAlternateIcons -> false
            app.alternateIconName == name -> true
            else -> suspendCancellableCoroutine { done -> app.setAlternateIconName(name) { error: NSError? -> done.resume(error == null) } }
        }
    }

    companion object {
        fun alternateIconName(icon: AppIcon): String? = if (icon == AppIcon.Leather) null else "AppIcon-${icon.name}"
    }
}
