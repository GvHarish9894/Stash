"""Generates the four launcher icon variants from the prototype's app-icon tile.

The prototype (`AppIconTile` in shared/.../ui/SettingsScreen.kt) draws a Playfair Display Bold Italic "S" in the
icon's foreground colour, centred on its background colour, at a font size of 28/48 of the tile. Adaptive icons show a
72 dp tile out of the 108 dp canvas, so the "S" is set at 28/48 * 72 = 42 dp and centred on its outline, well inside
the 66 dp safe zone. Provisional art: the handoff lists the final wordmark as an open question.

Run from the repository root after changing the font or the colours, with the pinned fontTools
(`pip install -r androidApp/launcher-icons/requirements.txt`):
    python3 androidApp/launcher-icons/generate.py
"""
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
FONT = ROOT / "core/resources/src/commonMain/composeResources/font/playfair_bold_italic.ttf"
RES = ROOT / "androidApp/src/main/res"

CANVAS = 108.0
FONT_SIZE = 28 / 48 * 72  # dp per em

# AppIcon in shared/.../model/Item.kt: name -> (background, foreground).
VARIANTS = {
    "leather": ("7A4E2D", "FBF6EA"),
    "night": ("1E1812", "E0B45C"),
    "parchment": ("F4ECD8", "7A4E2D"),
    "ink": ("2F4A6B", "F4ECD8"),
}


def glyph_path() -> str:
    font = TTFont(FONT)
    glyphs = font.getGlyphSet()
    glyph = glyphs[font.getBestCmap()[ord("S")]]
    bounds = BoundsPen(glyphs)
    glyph.draw(bounds)
    x_min, y_min, x_max, y_max = bounds.bounds
    scale = FONT_SIZE / font["head"].unitsPerEm
    # Font units are y-up; the vector is y-down. Centre the outline's box on the canvas.
    dx = CANVAS / 2 - (x_min + x_max) / 2 * scale
    dy = CANVAS / 2 + (y_min + y_max) / 2 * scale
    svg = SVGPathPen(glyphs, ntos=lambda v: f"{v:.2f}".rstrip("0").rstrip("."))
    glyph.draw(TransformPen(svg, (scale, 0, 0, -scale, dx, dy)))
    return svg.getCommands()


def vector(path: str, color: str) -> str:
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by androidApp/launcher-icons/generate.py; do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path
        android:fillColor="#FF{color}"
        android:pathData="{path}" />
</vector>
"""


def main() -> None:
    path = glyph_path()
    (RES / "drawable/ic_launcher_monochrome.xml").write_text(vector(path, "000000"))
    colors = ["<resources>", "    <!-- Generated by androidApp/launcher-icons/generate.py. -->"]
    for name, (background, foreground) in VARIANTS.items():
        colors.append(f'    <color name="launcher_{name}_background">#{background}</color>')
        (RES / f"drawable/ic_launcher_foreground_{name}.xml").write_text(vector(path, foreground))
        (RES / f"mipmap-anydpi-v26/ic_launcher_{name}.xml").write_text(f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by androidApp/launcher-icons/generate.py; do not edit. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/launcher_{name}_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground_{name}" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
""")
        (RES / f"mipmap-anydpi/ic_launcher_{name}.xml").write_text(f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by androidApp/launcher-icons/generate.py; do not edit. Before adaptive icons (API 24-25): the same
     layers on a rounded square. -->
<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
    <item>
        <shape android:shape="rectangle">
            <solid android:color="@color/launcher_{name}_background" />
            <corners android:radius="16dp" />
        </shape>
    </item>
    <item android:drawable="@drawable/ic_launcher_foreground_{name}" />
</layer-list>
""")
    colors.append("</resources>")
    (RES / "values/launcher_colors.xml").write_text("\n".join(colors) + "\n")


if __name__ == "__main__":
    main()
